        SqlConnection sqlConnection = new SqlConnection(@"Data Source=WIN-835DGRUVKSH;Initial Catalog=Restoran;Integrated Security=True;Trust Server Certificate=True");

        public void openConnection()
        {
            if (sqlConnection.State == System.Data.ConnectionState.Closed)
            {
                sqlConnection.Open();
            }
        }
        public void closeConnection()
        {
